# status.ps1 ??? Show the current state of the mcp-atlassian server
#
# Usage:
#   .\status.ps1
#   .\status.ps1 -Port 9002 -TaskName "Atlassian MCP Server"

param(
    [int]   $Port     = 9002,
    [string]$TaskName = "Atlassian MCP Server"
)

$ok = $true

# ?????? Process ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$procs = Get-Process | Where-Object {
    $_.Path -like "*uv\tools\mcp-atlassian*" -or $_.Name -eq "mcp-atlassian"
}

if ($procs) {
    Write-Host "Process   : RUNNING" -ForegroundColor Green
    $procs | ForEach-Object {
        Write-Host "            PID $($_.Id)  |  $($_.Path)"
    }
} else {
    Write-Host "Process   : NOT RUNNING" -ForegroundColor Red
    $ok = $false
}

# ?????? Health endpoint ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
try {
    $wr = [System.Net.HttpWebRequest]::Create("http://localhost:$Port/healthz")
    $wr.Timeout = 3000
    $resp = $wr.GetResponse()
    $rdr  = New-Object System.IO.StreamReader($resp.GetResponseStream())
    $body = $rdr.ReadToEnd() | ConvertFrom-Json
    Write-Host "Health    : OK  (http://localhost:$Port/healthz)" -ForegroundColor Green
    Write-Host "MCP URL   : http://localhost:$Port/mcp"
} catch {
    Write-Host "Health    : UNREACHABLE  (http://localhost:$Port/healthz)" -ForegroundColor Red
    $ok = $false
}

# ?????? Scheduled task ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($task) {
    $state = $task.State
    $color = if ($state -eq "Ready") { "Green" } else { "Yellow" }
    Write-Host "Scheduler : $state  (task: '$TaskName')" -ForegroundColor $color
} else {
    Write-Host "Scheduler : NOT REGISTERED  (run .\install.ps1 to set up auto-start)" -ForegroundColor Yellow
}

# ?????? Installed version ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$exeCmd = Get-Command mcp-atlassian -ErrorAction SilentlyContinue
if ($exeCmd) {
    Write-Host "Executable: $($exeCmd.Source)"
}

Write-Host ""
if ($ok) {
    Write-Host "Server is healthy." -ForegroundColor Green
    exit 0
} else {
    Write-Host "Server is not running. Run .\start.ps1 to start it." -ForegroundColor Red
    exit 1
}



