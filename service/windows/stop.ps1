# stop.ps1 ??? Stop all running mcp-atlassian server processes
#
# Usage:
#   .\stop.ps1
#   .\stop.ps1 -Port 9002

param(
    [int]$Port = 9002
)

$stopped = 0

# ?????? Kill by process path ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
Get-Process | Where-Object {
    $_.Path -like "*uv\tools\mcp-atlassian*" -or $_.Name -eq "mcp-atlassian"
} | ForEach-Object {
    Write-Host "  Stopping PID $($_.Id) ($($_.Name))..."
    Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
    $stopped++
}

# ?????? Also kill any process holding the port ?????????????????????????????????????????????????????????????????????????????????????????????????????????
Get-NetTCPConnection -LocalPort $Port -ErrorAction SilentlyContinue | ForEach-Object {
    $pid_ = $_.OwningProcess
    $proc = Get-Process -Id $pid_ -ErrorAction SilentlyContinue
    if ($proc -and $proc.Name -ne "System") {
        Write-Host "  Stopping PID $pid_ ($($proc.Name)) on port $Port..."
        Stop-Process -Id $pid_ -Force -ErrorAction SilentlyContinue
        $stopped++
    }
}

if ($stopped -gt 0) {
    Start-Sleep -Seconds 1
    Write-Host "Stopped $stopped process(es)." -ForegroundColor Green
} else {
    Write-Host "No running mcp-atlassian processes found." -ForegroundColor Gray
}


