# install.ps1 ??? Register mcp-atlassian as a Windows Task Scheduler job
# Runs at logon for the current user, hidden window, restarts on failure.
#
# Usage:
#   .\install.ps1
#   .\install.ps1 -VbsPath "C:\custom\path\start-atlassian-mcp.vbs"
#   .\install.ps1 -TaskName "My MCP Server"

param(
    [string]$TaskName = "Atlassian MCP Server",
    [string]$VbsPath  = "$env:USERPROFILE\start-atlassian-mcp.vbs"
)

$ErrorActionPreference = "Stop"

# ?????? Validate prerequisites ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
if (-not (Test-Path $VbsPath)) {
    Write-Error "VBScript not found at: $VbsPath`nCreate it first -- see README Step 3."
    exit 1
}

$exe = Get-Command mcp-atlassian -ErrorAction SilentlyContinue
if (-not $exe) {
    Write-Error "mcp-atlassian.exe not found in PATH.`nRun: uv tool install --from . mcp-atlassian"
    exit 1
}

# ?????? Remove existing task if present ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Write-Host "Removing existing task '$TaskName'..." -ForegroundColor Yellow
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}

# ?????? Register ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$action   = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "`"$VbsPath`""
$trigger  = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$settings = New-ScheduledTaskSettingsSet `
    -ExecutionTimeLimit (New-TimeSpan -Seconds 0) `
    -MultipleInstances IgnoreNew `
    -RestartCount 3 `
    -RestartInterval (New-TimeSpan -Minutes 1)

Register-ScheduledTask `
    -TaskName $TaskName `
    -Action   $action `
    -Trigger  $trigger `
    -Settings $settings `
    -Force | Out-Null

Write-Host "Task '$TaskName' registered -- will start at next logon." -ForegroundColor Green
Write-Host "  To start it now without logging off, run:  .\start.ps1"



