# uninstall.ps1 ??? Remove the mcp-atlassian Task Scheduler job and stop any running instance
#
# Usage:
#   .\uninstall.ps1
#   .\uninstall.ps1 -TaskName "My MCP Server"

param(
    [string]$TaskName = "Atlassian MCP Server"
)

$ErrorActionPreference = "Stop"

# ?????? Stop running process first ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
Write-Host "Stopping any running mcp-atlassian processes..." -ForegroundColor Yellow
Get-Process | Where-Object {
    $_.Path -like "*uv\tools\mcp-atlassian*" -or $_.Name -eq "mcp-atlassian"
} | ForEach-Object {
    Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
    Write-Host "  Stopped PID $($_.Id) ($($_.Name))"
}

# ?????? Remove scheduled task ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
$task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($task) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    Write-Host "Scheduled task '$TaskName' removed." -ForegroundColor Green
} else {
    Write-Host "  Task '$TaskName' was not registered -- nothing to remove." -ForegroundColor Gray
}

Write-Host "Uninstall complete." -ForegroundColor Green


