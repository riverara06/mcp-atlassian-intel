# start.ps1 ??? Start the mcp-atlassian server by running the VBScript
#
# Usage:
#   .\start.ps1
#   .\start.ps1 -VbsPath "C:\custom\path\start-atlassian-mcp.vbs"
#   .\start.ps1 -Port 9002 -HealthCheckTimeout 20

param(
    [string]$VbsPath            = "$env:USERPROFILE\start-atlassian-mcp.vbs",
    [int]   $Port               = 9002,
    [int]   $HealthCheckTimeout = 15
)

$ErrorActionPreference = "Stop"

# ?????? Check if already running ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
try {
    $r = Invoke-RestMethod "http://localhost:$Port/healthz" -ErrorAction Stop
    Write-Host "Server is already running on port $Port (status: $($r.status))." -ForegroundColor Yellow
    exit 0
} catch { <# not running ??? continue #> }

# ?????? Validate VBScript ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
if (-not (Test-Path $VbsPath)) {
    Write-Error "VBScript not found at: $VbsPath`nCreate it first -- see README Step 3."
    exit 1
}

# ?????? Launch ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
Write-Host "Starting mcp-atlassian via $VbsPath ..." -ForegroundColor Cyan
wscript.exe $VbsPath

# ?????? Wait for health check ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
Write-Host "Waiting for server on port $Port..." -NoNewline
$elapsed = 0
while ($elapsed -lt $HealthCheckTimeout) {
    Start-Sleep -Seconds 1; $elapsed++
    try {
        $r = Invoke-RestMethod "http://localhost:$Port/healthz" -ErrorAction Stop
        Write-Host ""
        Write-Host "Server is UP on http://localhost:$Port/mcp (status: $($r.status))" -ForegroundColor Green
        exit 0
    } catch {
        Write-Host "." -NoNewline
    }
}

Write-Host ""
Write-Error "Server did not respond within $HealthCheckTimeout seconds. Check the VBScript and CONFLUENCE_URL settings."
exit 1



